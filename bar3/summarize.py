"""Print practice-choosing runs (PRACTICE.md): one line per run, or round by round.

    ~/github/sotaku/venv/bin/python -m bar3.summarize --table bar3/records/*_r1.jsonl
    ~/github/sotaku/venv/bin/python -m bar3.summarize --effort bar3/records/*_r1.jsonl     # how hard each was tried
    ~/github/sotaku/venv/bin/python -m bar3.summarize bar3/records/ct2_r1.jsonl

Round by round: the pool, what the probes found, what was picked (with the curated tasks each picked problem's routine
solves, run on that task's own instances: the objective comparison with arm B's list), the routines and merges, and
the target attempt. Search is counted over every job: probes, lookaheads, practice and target searches.
"""

from __future__ import annotations

import collections
import json
import sys

import numpy as np

from library import dsl
from library.inventing import brm
from library.inventing.jobs import machine_for
from bar3 import problems as P

KINDS = ("target_probe", "probe_a", "probe_b", "look", "practice", "target")
LAWS = {}           # law formulas regenerated by name (the r1 records' text has a substitution slip: "mXx")


def load(path):
    return [json.loads(l) for l in open(path) if l.strip()]


def covers(prog, lib, k):
    """The curated tasks (arm B's list, without the target) that prog solves on their own instances at k and k2."""
    pl = {t: dsl.parse(v) for t, v in lib.items()}
    p = dsl.parse(prog)
    out = []
    for c in P.curated(k):
        ok = True
        for xs, Ns, w, size in ((c.xs, c.Ns, c.want, k), (c.cx, c.cN, c.cw, P.K2)):
            got, dead = brm.evaluate(p, pl, np.array(xs), np.array(Ns), machine_for(size))
            if dead or not (got == np.array(w)).all():
                ok = False
                break
        if ok:
            out.append(c.name.split("/")[1])
    return out


def totals(recs):
    return recs[-1]["totals"] if recs else {}


def config_of(name):
    """The learner config a run was launched from (its name minus the launch tag)."""
    from bar3.learner import CONFIGS
    base = name.rsplit("_r", 1)[0] if "_r" in name else name
    return base, CONFIGS.get(base, {})


SRC = {"law": "a", "law2": "a2", "restrict": "r", "project": "p", "value": "v", "remainder": "m", "dream": "d"}


def table(paths):
    print("| run | rule | sources | routines | rounds | x² mod N | routines made | states | search-hours | "
          "of which choosing |\n|---|---|---|---|---|---|---|---|---|---|")
    for path in paths:
        recs = load(path)
        if not recs:
            continue
        base, cfg = config_of(recs[0]["config"])
        srcs = "curated" if cfg.get("rule") == "curated" else "+".join(SRC[x] for x in cfg.get("sources", ()))
        how = cfg.get("routine", "simplest")
        how = "v2 clean" if how == "clean" else "v1 first"
        t = totals(recs)
        states = sum(v["states"] for v in t.values())
        hours = sum(v["seconds"] for v in t.values()) / 3600
        choose = sum(t.get(k, {}).get("seconds", 0) for k in ("probe_a", "probe_b", "look", "target_probe")) / 3600
        gen = next((r for r in recs if r.get("general")), None)
        found = f"round {gen['round']}: `{gen['general']['program']}`" if gen else "no"
        n_rt = sum(len(r["solved"]) for r in recs)
        print(f"| {recs[0]['config']} | {recs[0]['rule']} | {srcs} | {how} | {len(recs)} | {found} | {n_rt} | "
              f"{states / 1e6:,.1f}M | {hours:.2f} | {choose:.2f} |")


def effort(paths):
    """How hard each run was tried: rounds finished, the budgets, and every stage's jobs, states and hours."""
    print("| run | rounds finished | outcome | probe jobs (a / b) | lookaheads | practice searches | target searches "
          "| states | search-hours |\n|---|---|---|---|---|---|---|---|---|")
    for path in paths:
        recs = load(path)
        if not recs:
            continue
        t = recs[-1]["totals"]
        j = lambda k: t.get(k, {}).get("jobs", 0)                        # noqa: E731
        gen = next((r for r in recs if r.get("general")), None)
        out = f"general in round {gen['round']}" if gen else "not found"
        states = sum(v["states"] for v in t.values())
        hours = sum(v["seconds"] for v in t.values()) / 3600
        print(f"| {recs[0]['config']} | {len(recs)} | {out} | {j('probe_a')} / {j('probe_b')} | {j('look')} | "
              f"{j('practice')} | {j('target')} | {states / 1e6:,.1f}M | {hours:.2f} |")


def detail(path):
    recs = load(path)
    print(f"### {recs[0]['config']} (rule {recs[0]['rule']}, k = {recs[0]['k']})")
    prev = {}
    for r in recs:
        st = collections.Counter(v.get("status", "practice " + v.get("practice", "?")) for v in r["status"].values())
        src = collections.Counter(c["source"] for c in r["pool"])
        print(f"\nround {r['round']}: pool {len(r['pool'])} {dict(src)}; probes {dict(st)}; "
              f"target probe best {r['target_probe']['best_fit']} (mdl {r['mdl0']:.1f})")
        forms = {c["name"]: c["formula"] for c in r["pool"]}
        forms.update({c.name: c.formula for c in LAWS.get(r["k"]) or LAWS.setdefault(r["k"], P.laws(r["k"]))})
        for name in r["picked"]:
            s = r["status"].get(name, {})
            cov = covers(s["best"], r["lib"], r["k"]) if s.get("best") else []
            sc = r["scores"].get(name)
            print(f"  picked {name}: {forms.get(name, '')}")
            print(f"     {s.get('status')} cost {s.get('cost')} `{s.get('best', '')}`"
                  + (f" gain {sc:.1f}" if sc is not None else "") + (f" | solves curated {cov}" if cov else ""))
        if r["pairs"]:
            print("  best pairs:", [(round(g, 1), a, b, c) for g, a, b, c in r["pairs"][:5]])
        for e in r["merges"] + r["promoted"]:
            print(f"    + {e['name']} = {e['def']}    ({e.get('expands_to', '')})")
        tr = r["target"]
        print(f"  target: cost {tr and tr['found_cost']} levels {tr and tr['level_sizes']} stop {tr and tr['stop']}")
        if tr and tr.get("programs"):
            for p in tr["programs"][:4]:
                print(f"     {p['program']}  (general {p.get('general')})  = {p['primitive']}")
        t = r["totals"]
        step = {k: (t.get(k, {}).get("states", 0) - prev.get(k, {}).get("states", 0)) for k in KINDS}
        print("  states this round:", {k: f"{v / 1e6:.2f}M" for k, v in step.items() if v})
        prev = t
    t = totals(recs)
    print("\ntotal:", {k: f"{v['jobs']} jobs, {v['states'] / 1e6:.1f}M states, {v['seconds'] / 3600:.2f} h"
                       for k, v in t.items()})


def main():
    if sys.argv[1] == "--table":
        return table(sys.argv[2:])
    if sys.argv[1] == "--effort":
        return effort(sys.argv[2:])
    for path in sys.argv[1:]:
        detail(path)


if __name__ == "__main__":
    main()
