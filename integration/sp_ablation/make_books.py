"""The two books of SP_ABLATION.md §5, as copies of sp2 (integration/self_practice/submission_stage3_sp2.py, md5
afc70fe9, asserted, never written):
  * book_min: sp2 posing only the laws and patterns the leave-one-out arms found needed (SelfClimb's laws= and
    patterns=, as make_variants.py's book arms);
  * book_gen: sp2 with its hand-written book (PATTERNS, LAW_BOOK, Draw, law_target) replaced by the generated one
    (genbook.py's two blocks): numbers by the division law's form, every operation on every pattern, one set of
    target rules for all.
Writes variants/<book>.py and adds them to variants/MD5SUMS.json and plans/arms.json.

    ~/github/sotaku/venv/bin/python integration/sp_ablation/make_books.py [--force]
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import make_variants as MV  # noqa: E402

# the smallest book the leave-one-out arms allow (SP_ABLATION.md §5): every law and pattern whose own arm certified
# without it is dropped (x+dn too, which only cost time)
MIN_LAWS = ("lt", "red", "add", "mul", "acc.mul")
MIN_PATTERNS = ("pair", "x+on", "x,o", "o,x,d")

SP2_BOOK_START = "# A pattern: the instance kinds (one data term per operand; probe i is of kind i mod len), how many"
SP2_BOOK_END = 'GROW = {"same": 0, "carry": 1, "double": 2}\n'
SP2_DRAW_START = "class Draw:\n"
SP2_DRAW_END = "class Goal:\n"


def block(src, start, end):
    """The text from the line `start` (included) to `end` (excluded): the one place it occurs."""
    i = src.index(start)
    j = src.index(end, i)
    assert src.count(start) == 1 and src[i:].count(end) >= 1, (start, end)
    return src[i:j]


def gen_blocks():
    g = (HERE / "genbook.py").read_text()
    book = block(g, "# ---8<--- book\n", "# ---8<--- end book\n")[len("# ---8<--- book\n"):]
    draw = block(g, "# ---8<--- draw\n", "# ---8<--- end draw\n")[len("# ---8<--- draw\n"):]
    return book, draw


def books(src):
    book, draw = gen_blocks()
    old_book = src[src.index(SP2_BOOK_START):src.index(SP2_BOOK_END) + len(SP2_BOOK_END)]
    old_draw = block(src, SP2_DRAW_START, SP2_DRAW_END)
    return {
        "book_min": ("the smallest book the leave-one-out arms allow: laws " + ", ".join(MIN_LAWS) + " on patterns " +
                     ", ".join(MIN_PATTERNS),
                     MV.book(laws=MIN_LAWS, patterns=MIN_PATTERNS, why="the needed ones, SP_ABLATION.md §5")),
        "book_gen": ("the book generated by a grammar (integration/sp_ablation/genbook.py): numbers by the division "
                     "law's form, every operation on every pattern, one set of target rules",
                     [(old_book, book), (old_draw, draw + "\n\n")]),
    }


def main(argv):
    src = MV.SP2.read_text()
    assert hashlib.md5(src.encode()).hexdigest() == MV.SP2_MD5, "sp2 changed"
    sums_path = MV.OUT / "MD5SUMS.json"
    sums = json.loads(sums_path.read_text())
    arms_path = HERE / "plans" / "arms.json"
    arms = json.loads(arms_path.read_text())
    for name, (what, edits) in books(src).items():
        MV.ARMS[name] = (what, edits)
        out = MV.build(name, src)
        path = MV.OUT / f"{name}.py"
        if path.exists() and path.read_text() != out and "--force" not in argv:
            raise SystemExit(f"{path} differs from this build (pass --force to replace it)")
        path.write_text(out)
        md5 = hashlib.md5(out.encode()).hexdigest()
        sums["variants"][name] = {"md5": md5, "what": what}
        arms[name] = {"file": f"integration/sp_ablation/variants/{name}.py", "what": what}
        print(f"{name:10s} {md5} {len(out.encode()):,} bytes  {what}")
        assert len(out.encode()) <= 256 * 1024, "over the 256 KiB limit"
    sums_path.write_text(json.dumps(sums, indent=1) + "\n")
    arms_path.write_text(json.dumps(arms, indent=1) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
